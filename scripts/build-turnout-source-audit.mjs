function csvValue(value) {
  const text = String(value ?? "");
  if (/[",\r\n]/.test(text)) {
    return `"${text.replaceAll('"', '""')}"`;
  }
  return text;
}

function rowToCsv(row) {
  return headers.map((header) => csvValue(row[header])).join(",");
}

function statusLabel(status) {
  return status
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join(" ");
}

function markdownTable(items) {
  const lines = [
    "| State | Status | Source Level | Parser Fit | Caveat |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const row of items) {
    lines.push(`| ${row.state} | ${statusLabel(row.status)} | ${row.source_level} | ${row.parser_fit} | ${row.caveats.replaceAll("|", "/")} |`);
  }
  return lines.join("\n");
}

function writeAudit() {
  if (rows.length !== 50) {
    throw new Error(`Expected 50 state rows, got ${rows.length}.`);
  }
  const states = new Set(rows.map((row) => row.state));
  if (states.size !== 50) {
    throw new Error(`Expected 50 unique states, got ${states.size}.`);
  }
  for (const row of rows) {
    for (const header of headers) {
      if (!(header in row) && header !== "checked_at") {
        throw new Error(`${row.state} is missing ${header}.`);
      }
    }
    row.checked_at = CHECKED_AT;
  }

  const csv = `${headers.join(",")}\n${rows.map(rowToCsv).join("\n")}\n`;
  const json = {
    metadata: {
      title: "Turnout-first source audit",
      checked_at: CHECKED_AT,
      row_count: rows.length,
      schema: headers,
      notes: [
        "This audit is source discovery and documentation only; it does not enable turnout capabilities.",
        "A source is marked usable only when it appears to provide ballots cast plus registered-voter or eligible-voter denominators.",
        "Denominator timing follows the app importer vocabulary: final, postElectionDay, preElectionDay, or unknown.",
      ],
    },
    rows,
  };

  const byStatus = rows.reduce((map, row) => {
    map.set(row.status, (map.get(row.status) || 0) + 1);
    return map;
  }, new Map());
  const loaded = rows.filter((row) => row.status === "loaded");
  const partial = rows.filter((row) => row.status === "partial_loaded");
  const ready = rows.filter((row) => row.status === "usable_candidate");
  const parser = rows.filter((row) => row.status === "parser_needed");
  const review = rows.filter((row) => row.status === "source_needs_review");
  const local = rows.filter((row) => row.status === "county_local_required");

  const summary = [
    "# Turnout Source Audit",
    "",
    `Checked: ${CHECKED_AT}`,
    "",
    "This audit captures Leif's highest-priority missing data for all 50 states: ballots-cast turnout rows plus registered-voter or eligible-voter denominators, preferably at precinct/VTD/ward level. It is a handoff pack only; no state config capabilities were changed.",
    "",
    "## Coverage Summary",
    "",
    ...[...byStatus.entries()]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([status, count]) => `- ${statusLabel(status)}: ${count}`),
    "",
    "Known-good loaded states remain AL, FL, MI, MN, ND, and PA. Wisconsin is partial because the WEC statewide ward results do not include denominator fields and only some local turnout rows have been imported.",
    "",
    "## Best Next Imports",
    "",
    "The quickest wins are states marked `usable_candidate`: they appear to have official statewide or state-hosted county turnout denominator sources and mainly need download/parser work. States marked `parser_needed` already have strong official sources but need source-specific mapping. States marked `source_needs_review` need a scripted portal/export capture or field confirmation. States marked `county_local_required` likely need county-by-county official report collection.",
    "",
    "## Loaded Or Partial",
    "",
    markdownTable([...loaded, ...partial]),
    "",
    "## Usable Candidates",
    "",
    markdownTable(ready),
    "",
    "## Parser Needed",
    "",
    markdownTable(parser),
    "",
    "## Needs Source Review",
    "",
    markdownTable(review),
    "",
    "## County-Local Collection",
    "",
    markdownTable(local),
    "",
    "## Files",
    "",
    "- `data/turnout-source-audit.csv`",
    "- `data/turnout-source-audit.json`",
  ].join("\n");

  fs.writeFileSync(path.join("data", "turnout-source-audit.csv"), csv, "utf8");
  fs.writeFileSync(path.join("data", "turnout-source-audit.json"), `${JSON.stringify(json, null, 2)}\n`, "utf8");
  fs.writeFileSync(path.join("docs", "turnout-source-audit.md"), `${summary}\n`, "utf8");
}

writeAudit();
